import type { Financials } from '../api/types'
import { formatCompact, formatDate, formatPrice } from '../lib/format'

export function FinancialTable({ financials }: { financials: Financials }) {
  const { years, currency } = financials
  if (years.length === 0) return null
  // Oldest to newest, the way a trend reads.
  const ordered = [...years].reverse()
  const rows = [
    ['Revenue', (y: (typeof years)[number]) => formatCompact(y.revenue, currency)],
    ['Net income', (y: (typeof years)[number]) => formatCompact(y.net_income, currency)],
    ['Diluted EPS', (y: (typeof years)[number]) => formatPrice(y.eps_diluted, currency)],
  ] as const

  return (
    <section className="rounded-lg border border-slate-200 bg-white p-5">
      <h3 className="font-semibold">Annual financials</h3>
      <p className="mt-0.5 text-xs text-slate-500">Reported figures from SEC data, not generated by AI.</p>
      <div className="mt-3 overflow-x-auto">
        <table className="w-full min-w-[32rem] text-sm tabular-nums">
          <thead>
            <tr className="border-b border-slate-200 text-xs text-slate-500">
              <th scope="col" className="py-2 pr-4 text-left font-medium">
                Fiscal year ended
              </th>
              {ordered.map((year) => (
                <th key={year.period_end} scope="col" className="py-2 pl-4 text-right font-medium">
                  {formatDate(year.period_end)}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map(([label, value]) => (
              <tr key={label} className="border-b border-slate-100 last:border-0">
                <th scope="row" className="py-2 pr-4 text-left font-medium">
                  {label}
                </th>
                {ordered.map((year) => (
                  <td key={year.period_end} className="py-2 pl-4 text-right">
                    {value(year)}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {financials.warnings.map((warning) => (
        <p key={warning} className="mt-2 text-xs text-amber-800">
          {warning}
        </p>
      ))}
    </section>
  )
}
